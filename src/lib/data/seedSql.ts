// Renders the sample data set as supabase/seed.sql. Run `npm run db:seed:generate`
// after changing sample.ts; a unit test fails if the file is out of date.

import type { SampleDataset } from "./sample";

const quote = (text: string) => `'${text.replace(/'/g, "''")}'`;
const lit = (v: unknown) =>
  v === null || v === undefined ? "null" : typeof v === "number" ? String(v) : quote(String(v));
const json = (v: unknown) => `${quote(JSON.stringify(v))}::jsonb`;

export function renderSeedSql(data: SampleDataset): string {
  const estimates = data.estimates.map(
    (e) =>
      `  (${[
        lit(e.id),
        lit(e.clientName),
        lit(e.projectName),
        lit(e.status),
        lit(e.developer),
        lit(e.rate),
        lit(e.jobTitle),
        lit(e.jobDescription),
        lit(e.additionalInfo),
        json(e.links),
        json(e.rows),
        lit(e.createdAt),
        lit(e.readyAt),
        lit(e.archivedAt),
        lit(e.updatedAt),
      ].join(", ")})`,
  );
  return [
    "-- Sample data for local development and demos.",
    "-- GENERATED by scripts/generate-seed.ts from src/lib/data/sample.ts. Do not edit by hand.",
    "",
    "insert into public.estimates (id, client_name, project_name, status, developer, rate, job_title, job_description, additional_info, links, rows, created_at, ready_at, archived_at, updated_at) values",
    `${estimates.join(",\n")};`,
    "",
  ].join("\n");
}
